board = [["."] * 8 for _ in range(8)]
pos = input()

# Переводим координаты в индексы матрицы
c = ord(pos[0]) - ord('a')
r = 8 - int(pos[1])
# Ставим коня
board[r][c] = "N"

# Все 8 возможных ходов коня (сдвиг по строке, сдвиг по столбцу)
moves = [[-2, -1], [-2, 1], [-1, -2], [-1, 2], [1, -2], [1, 2], [2, -1], [2, 1]]

# Отмечаем клетки, которые бьёт конь
for move in moves:
    nr = r + move[0]
    nc = c + move[1]
    # Проверяем, не выходят ли новые индексы за пределы доски 8x8
    if 0 <= nr < 8 and 0 <= nc < 8:
        board[nr][nc] = "*"

for row in board:
	print(*row)