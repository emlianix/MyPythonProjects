numbers = [8, 9, 10, 11]

# 1. Заменить второй элемент (индекс 1) на 17
numbers[1] = 17
# 2. Добавить числа 4, 5 и 6 в конец списка
numbers.extend([4, 5, 6])
# 3. Удалить первый элемент (индекс 0)
del numbers[0]
# 4. Удвоить список
numbers = numbers * 2
# 5. Вставить число 25 по индексу 3
numbers.insert(3, 25)

print(numbers)